"""Writes a hash-pinned requirements file from a requirements/*.in file.

pip evaluates environment markers for the machine it runs on, so each
supported platform is resolved on that platform. A package that only some
platforms need gets a sys_platform marker.

    # On each platform (for example macOS, then a Linux container):
    python scripts/lock.py resolve requirements/package.in package-linux.json
    # Then, anywhere, combine the reports into requirements/package.txt:
    python scripts/lock.py write requirements/package.in \\
        package-macos.json package-linux.json

write fetches the SHA-256 of every file of each pinned release from PyPI, so
the lock also installs on CPU architectures the resolution did not run on.
Run resolve with the interpreter the lock is for (the CPython 3.14 tool
interpreter for tool locks, any supported interpreter for runtime locks).
"""

import argparse
import json
import platform
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

PYPI_JSON = "https://pypi.org/pypi/{name}/{version}/json"


def normalize(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def resolve(requirements_in, report):
    """Resolve requirements_in for this machine without installing it."""
    subprocess.run(
        [
            sys.executable,
            "-m",
            "pip",
            "install",
            "--dry-run",
            "--ignore-installed",
            "--only-binary",
            ":all:",
            "--quiet",
            "--report",
            str(report),
            "-r",
            str(requirements_in),
        ],
        check=True,
    )


def read_report(path):
    """(platform, {name: (version, sha256 of the chosen file)})"""
    report = json.loads(Path(path).read_text())
    environment = report["environment"]
    pins = {}
    for item in report["install"]:
        hashes = item["download_info"]["archive_info"]["hashes"]
        pins[normalize(item["metadata"]["name"])] = (
            item["metadata"]["version"],
            hashes["sha256"],
        )
    return environment, pins


def release_hashes(name, version):
    with urllib.request.urlopen(
        PYPI_JSON.format(name=name, version=version)
    ) as page:
        files = json.load(page)["urls"]
    return sorted(file["digests"]["sha256"] for file in files)


def write(requirements_in, reports):
    resolutions = [read_report(report) for report in reports]
    names = sorted({name for _env, pins in resolutions for name in pins})

    lines = []
    for name in names:
        versions = {
            pins[name][0] for _env, pins in resolutions if name in pins
        }
        if len(versions) != 1:
            sys.exit(
                f"{name} resolved to different versions: {sorted(versions)}"
            )
        version = versions.pop()

        present = {
            env["sys_platform"] for env, pins in resolutions if name in pins
        }
        absent = {
            env["sys_platform"]
            for env, pins in resolutions
            if name not in pins
        }
        if present & absent:
            sys.exit(
                f"{name} is needed on only some {sorted(present & absent)} "
                "resolutions, which a sys_platform marker cannot express"
            )
        marker = ""
        if absent:
            marker = " ; " + " or ".join(
                f'sys_platform == "{sys_platform}"'
                for sys_platform in sorted(present)
            )

        hashes = release_hashes(name, version)
        for _env, pins in resolutions:
            if name in pins and pins[name][1] not in hashes:
                sys.exit(f"{name}=={version}: resolved file is not on PyPI")
        lines.append(
            f"{name}=={version}{marker} \\\n"
            + " \\\n".join(f"    --hash=sha256:{digest}" for digest in hashes)
        )

    platforms = ", ".join(
        f"{env['implementation_name']} {env['python_version']} "
        f"{env['sys_platform']} {env['platform_machine']}"
        for env, _pins in resolutions
    )
    header = (
        f"# Generated by scripts/lock.py from {Path(requirements_in).name}. "
        "Do not edit; see that script.\n"
        f"# Resolved on: {platforms}.\n"
    )
    output = Path(requirements_in).with_suffix(".txt")
    output.write_text(header + "\n".join(lines) + "\n")
    print(f"wrote {output} ({len(lines)} packages)")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)
    resolve_parser = commands.add_parser("resolve")
    resolve_parser.add_argument("requirements_in")
    resolve_parser.add_argument("report")
    write_parser = commands.add_parser("write")
    write_parser.add_argument("requirements_in")
    write_parser.add_argument("reports", nargs="+")
    args = parser.parse_args()

    if args.command == "resolve":
        resolve(args.requirements_in, args.report)
        print(f"resolved on {platform.platform()} into {args.report}")
    else:
        write(args.requirements_in, args.reports)


if __name__ == "__main__":
    main()
